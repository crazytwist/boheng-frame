-- Transport 静态路线配置。仅保存路线规划，不保存运输执行数据。
CREATE TABLE IF NOT EXISTS `transport_route_config` (
    `id` bigint NOT NULL AUTO_INCREMENT,
    `route_code` varchar(64) NOT NULL,
    `route_name` varchar(128) NOT NULL,
    `route_type` varchar(32) NOT NULL DEFAULT 'AGV',
    `source_type` varchar(32) NOT NULL,
    `source_station_code` varchar(64) NOT NULL,
    `source_area_code` varchar(64) DEFAULT NULL COMMENT 'WMS查询起点中转位的区域',
    `target_type` varchar(32) NOT NULL,
    `target_station_code` varchar(64) NOT NULL,
    `target_area_code` varchar(64) DEFAULT NULL COMMENT 'WMS查询终点中转位的区域',
    `move_action_key` varchar(128) NOT NULL COMMENT '如 AGV#move',
    `grab_action_key` varchar(128) NOT NULL COMMENT '如 AGV#grab',
    `place_action_key` varchar(128) NOT NULL COMMENT '如 AGV#place',
    `warehouse_load_action_key` varchar(128) DEFAULT NULL,
    `warehouse_unload_action_key` varchar(128) DEFAULT NULL,
    `agv_task_type` varchar(64) DEFAULT NULL,
    `plate_type` varchar(64) DEFAULT NULL,
    `agv_load_capacity` int NOT NULL DEFAULT 1,
    `door_required` tinyint NOT NULL DEFAULT 0,
    `door_open_action_key` varchar(128) DEFAULT NULL,
    `door_close_action_key` varchar(128) DEFAULT NULL,
    `flow_definition_key` varchar(128) DEFAULT NULL,
    `flow_definition_version` int DEFAULT NULL,
    `priority` int NOT NULL DEFAULT 0,
    `enabled` tinyint NOT NULL DEFAULT 1,
    `remark` varchar(512) DEFAULT NULL,
    `creator` varchar(64) NOT NULL DEFAULT '',
    `create_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `updater` varchar(64) NOT NULL DEFAULT '',
    `update_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    `deleted` bit(1) NOT NULL DEFAULT b'0',
    `tenant_id` bigint NOT NULL DEFAULT 0,
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_transport_route_code` (`tenant_id`, `route_code`, `deleted`),
    KEY `idx_transport_route_source_target` (`tenant_id`, `source_station_code`, `target_station_code`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='Transport静态路线配置';
